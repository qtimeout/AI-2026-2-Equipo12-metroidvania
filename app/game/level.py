from .config import SPAWN_CHARS

# Cada nivel: nombre del área (título al entrar), tema visual (grupo de piezas en app/assets) y mapa.
LEVELS = {
    1: {"nombre": "PASO OLVIDADO", "tema": "kingspass", "mapa": LEVEL_1},
    2: {"nombre": "CRUCES OLVIDADOS", "tema": "crossroads", "mapa": LEVEL_2},
    3: {"nombre": "SENDERO VERDE", "tema": "greenpath", "mapa": LEVEL_3},
    4: {"nombre": "GUARIDA DE HORNET", "tema": "greenpath", "paleta": "arena", "mapa": LEVEL_4, "jefe": True},
}


class Level:
    def __init__(self, n=1, rows=None):
        info = LEVELS[n]
        self.n = n
        self.name = info["nombre"]
        self.theme = info["tema"]
        self.palette = info.get("paleta", self.theme)
        self.boss = info.get("jefe", False)
        rows = rows or info["mapa"]
        self.h = len(rows)
        self.w = len(rows[0])
        assert all(len(r) == self.w for r in rows), "todas las filas deben tener el mismo ancho"
        self.player_spawn = self.enemy_spawn = self.exit = self.boss_spawn = None
        self.enemy_spawns = []           # [(celda, tipo)] en orden de lectura
        grid = []
        for r, row in enumerate(rows):
            line = []
            for c, ch in enumerate(row):
                if ch == "P":
                    self.player_spawn = (c, r)
                elif ch == "X":
                    self.exit = (c, r)
                elif ch == "B":
                    self.boss_spawn = (c, r)
                elif ch in SPAWN_CHARS:
                    self.enemy_spawns.append(((c, r), SPAWN_CHARS[ch]))
                    if ch == "E":
                        self.enemy_spawn = (c, r)
                line.append(ch == "#")
            grid.append(line)
        self._solid = grid

    @property
    def has_next(self):
        return self.n + 1 in LEVELS

    def solid(self, c, r):
        if c < 0 or r < 0 or c >= self.w or r >= self.h:
            return True
        return self._solid[r][c]

    def standable(self, c, r):
        """Una celda es pisable si está vacía y tiene suelo debajo."""
        return not self.solid(c, r) and self.solid(c, r + 1)
